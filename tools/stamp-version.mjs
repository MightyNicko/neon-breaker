// Writes src/version.js as v<major.minor>.<MMdd>.<hhmm> using local time. Run before every commit/release.
import { writeFileSync } from 'node:fs';
const BASE = '0.1';
const d = new Date(), p = (n) => String(n).padStart(2, '0');
const v = `v${BASE}.${p(d.getMonth() + 1)}${p(d.getDate())}.${p(d.getHours())}${p(d.getMinutes())}`;
writeFileSync(new URL('../src/version.js', import.meta.url), `// Generated by tools/stamp-version.mjs. Do not edit by hand.\nexport const VERSION = '${v}';\n`);
console.log(v);
